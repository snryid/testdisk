export function t(lang, key, vars = {}) {
  const value = messages[lang]?.[key] ?? messages.en[key] ?? key;
  if (typeof value === "string") {
    return Object.entries(vars).reduce(
      (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
      value
    );
  }
  return value;
}

