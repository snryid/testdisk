export function t(lang, key, vars = {}) {
  const value = messages[lang]?.[key] ?? messages.en[key] ?? key;
  if (typeof value === "string") {
    return Object.entries(vars).reduce(
      (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
      value
    );
  }
  return value;
}

export function filesystemLabel(lang, value) {
  return messages[lang]?.filesystem_labels?.[value] ?? messages.en.filesystem_labels[value] ?? value;
}

export function partitionTableTypeLabel(lang, value) {
  return messages[lang]?.partition_table_type?.[value] ?? messages.en.partition_table_type[value] ?? value;
}
